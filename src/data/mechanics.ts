// Mechanic fund definitions, static content (matches the modularity principle in docs/ARCHITECTURE.md:
// adding a new mechanic is just a new entry here, no engine/UI code changes needed).
// Player progress (mastery values, foundation stats) lives in mockSave.ts, this file is definitions only.
//
// Design note: mechanics are NOT hard-gated behind each other. A real player can attempt Flip Reset before
// Ceiling Shot, they'll just be bad at it. So the only hard gate is era (can't train a move that hasn't
// been discovered in-universe yet). Everything else, foundation-stat readiness and having already trained
// a related mechanic, affects *efficiency* (how fast hours convert to mastery), not availability. This is
// the "fund" model: invest training hours in whatever you want, get better returns when you're prepared.
//
// eraStart dates are "vibes-accurate" community-discovery approximations for real Rocket League mechanics,
// not cited patch dates, see docs/DATA_MODEL.md's Meta Timeline section for why exact citations aren't the goal.
//
// ~80 mechanics across 10 branches (Movement, Ground Control, Flicks, Aerial Control, Pinches, Defensive
// Mechanics, Positioning, Kickoff, Passing, Boost Management), the Training screen's Mechanics tab uses a
// branch selector (one category visible at a time) rather than stacking all of them, so this stays
// browsable instead of overwhelming.

export type FoundationCategory = "carControl" | "aerialControl" | "boostManagement" | "offense" | "defense" | "passing";

export const FOUNDATION_LABELS: Record<FoundationCategory, string> = {
  carControl: "Car Control",
  aerialControl: "Aerial Control",
  boostManagement: "Boost Management",
  offense: "Offense",
  defense: "Defense",
  passing: "Passing Plays",
};

// "Mechanical" is pure freeplay execution, trainable anytime, no cost besides hours (same as the
// Mechanic Fund below). "Tactical" is decision-making/resource-management, you can't get better at these
// by yourself in a vacuum any more than real Game Sense, so each session costs a Skill Point earned from
// playing ranked. Boost Management lives here rather than under Mechanical on purpose, it's a tactical
// resource-management skill, not a raw car-control one.
export const FOUNDATION_GROUPS: { label: string; categories: FoundationCategory[]; costsSkillPoint: boolean }[] = [
  { label: "Mechanical", categories: ["carControl", "aerialControl"], costsSkillPoint: false },
  { label: "Tactical", categories: ["boostManagement", "offense", "defense", "passing"], costsSkillPoint: true },
];

export const TACTICAL_FOUNDATION_CATEGORIES: FoundationCategory[] = ["boostManagement", "offense", "defense", "passing"];


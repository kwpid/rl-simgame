const SYNERGY_BONUS_PER_MECHANIC = 15; // % efficiency bonus per already-trained recommended-after mechanic
const MAX_SYNERGY_BONUS = 30;
const MIN_EFFICIENCY_FLOOR = 25; // even completely undertrained, progress is slow, never impossible
const MAX_EFFICIENCY = 150;

export interface MechanicAvailability {
  discovered: boolean;
  eraDetail?: string;          // only set when !discovered
  statReadiness: number;       // 0-100+, % of recommendedStatValue currently met (100 if no stat requirement)
  synergyBonus: number;        // 0-30, % bonus from already-trained recommendedAfter mechanics
  efficiency: number;          // overall %, how fast training hours convert to mastery here
}

export function getMechanicAvailability(
  def: MechanicDefinition,
  currentDate: { year: number; month: number },
  foundationStats: Record<FoundationCategory, number>,
  mechanicProgress: Record<string, { currentValue: number }>
): MechanicAvailability {
  const eraReached =
    currentDate.year > def.eraStart.year ||
    (currentDate.year === def.eraStart.year && currentDate.month >= def.eraStart.month);

  if (!eraReached) {
    const monthName = new Date(def.eraStart.year, def.eraStart.month - 1).toLocaleString("en-US", { month: "short" });
    return {
      discovered: false,
      eraDetail: `Not discovered until ${monthName} ${def.eraStart.year}`,
      statReadiness: 0,
      synergyBonus: 0,
      efficiency: 0,
    };
  }

  const statReadiness = def.recommendedStat && def.recommendedStatValue
    ? Math.round((foundationStats[def.recommendedStat] / def.recommendedStatValue) * 100)
    : 100;

  const trainedSynergyCount = (def.recommendedAfter ?? []).filter(
    (id) => (mechanicProgress[id]?.currentValue ?? 0) > 0
  ).length;
  const synergyBonus = Math.min(MAX_SYNERGY_BONUS, trainedSynergyCount * SYNERGY_BONUS_PER_MECHANIC);

  const baseEfficiency = Math.max(MIN_EFFICIENCY_FLOOR, Math.min(100, statReadiness));
  const efficiency = Math.min(MAX_EFFICIENCY, baseEfficiency + synergyBonus);

  return { discovered: true, statReadiness, synergyBonus, efficiency };
}
